-- Video 346 — Fitness Database Sample Dataset
-- PostgreSQL

-- Visits for active members are stored relative to CURRENT_DATE,
-- so the 'last 30 days' queries return meaningful results whenever you run this.

--Note: If you're using this on a database other than Postgres, you'll probably need to modify these first few statements.

CREATE SCHEMA fitness_db;
SET search_path TO fitness_db;


DROP TABLE IF EXISTS visits;
DROP TABLE IF EXISTS memberships;
DROP TABLE IF EXISTS members;

CREATE TABLE members (
    member_id    INT PRIMARY KEY,
    name         VARCHAR(100) NOT NULL,
    email        VARCHAR(255) NOT NULL UNIQUE,
    joined_date  DATE NOT NULL
);

CREATE TABLE memberships (
    membership_id   INT PRIMARY KEY,
    member_id       INT NOT NULL REFERENCES members(member_id),
    started_at      DATE NOT NULL,
    ended_at        DATE,
    monthly_amount  NUMERIC(10,2) NOT NULL
);

CREATE TABLE visits (
    visit_id          INT PRIMARY KEY,
    member_id         INT NOT NULL REFERENCES members(member_id),
    visit_date        DATE NOT NULL,
    duration_minutes  INT NOT NULL
);

