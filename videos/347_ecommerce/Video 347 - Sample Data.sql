-- ------------------------------------------------------------
-- Customers
-- ------------------------------------------------------------

CREATE TABLE customer (
    customer_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(255) NOT NULL UNIQUE,
    password_hash  VARCHAR(255) NOT NULL,
    first_name     VARCHAR(100) NOT NULL,
    last_name      VARCHAR(100) NOT NULL,
    phone          VARCHAR(30),
    created_at     TIMESTAMP NOT NULL
);

CREATE TABLE country (
    country_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_name  VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE address (
    address_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    INT NOT NULL REFERENCES customer(customer_id),
    address_line1  VARCHAR(255) NOT NULL,
    address_line2  VARCHAR(255),
    city           VARCHAR(100) NOT NULL,
    region         VARCHAR(100),
    postal_code    VARCHAR(20),
    country_id     INT NOT NULL REFERENCES country(country_id),
    is_default     BOOLEAN NOT NULL DEFAULT false
);

-- One default address per customer
CREATE UNIQUE INDEX uq_address_default ON address (customer_id) WHERE is_default = true;

CREATE TABLE payment_type (
    payment_type_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_name        VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE payment_method (
    payment_method_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id        INT NOT NULL REFERENCES customer(customer_id),
    payment_type_id    INT NOT NULL REFERENCES payment_type(payment_type_id),
    provider           VARCHAR(50) NOT NULL,
    provider_token     VARCHAR(255) NOT NULL,
    card_brand         VARCHAR(30),
    last_four          CHAR(4),
    expiry_month       INT,
    expiry_year        INT,
    is_default         BOOLEAN NOT NULL DEFAULT false
);

-- One default payment method per customer
CREATE UNIQUE INDEX uq_payment_method_default ON payment_method (customer_id) WHERE is_default = true;

-- ------------------------------------------------------------
-- Products
-- ------------------------------------------------------------

CREATE TABLE category (
    category_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name       VARCHAR(100) NOT NULL,
    parent_category_id  INT REFERENCES category(category_id)
);

CREATE TABLE product (
    product_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name  VARCHAR(255) NOT NULL,
    description   TEXT,
    brand         VARCHAR(100),
    created_at    TIMESTAMP NOT NULL
);

CREATE TABLE product_category (
    product_id   INT NOT NULL REFERENCES product(product_id),
    category_id  INT NOT NULL REFERENCES category(category_id),
    PRIMARY KEY (product_id, category_id)
);

CREATE TABLE product_variant (
    variant_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    INT NOT NULL REFERENCES product(product_id),
    sku           VARCHAR(50) NOT NULL UNIQUE,
    price         DECIMAL(10,2) NOT NULL,
    qty_in_stock  INT NOT NULL DEFAULT 0
);

CREATE TABLE product_option (
    option_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id   INT NOT NULL REFERENCES product(product_id),
    option_name  VARCHAR(50) NOT NULL,
    UNIQUE (product_id, option_name)
);

CREATE TABLE product_option_value (
    option_value_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    option_id        INT NOT NULL REFERENCES product_option(option_id),
    value_name       VARCHAR(50) NOT NULL,
    UNIQUE (option_id, value_name),
    -- Target for the composite foreign key on variant_option_value
    UNIQUE (option_value_id, option_id)
);

CREATE TABLE variant_option_value (
    variant_id       INT NOT NULL REFERENCES product_variant(variant_id),
    option_id        INT NOT NULL,
    option_value_id  INT NOT NULL,
    -- A variant has only one value for each option
    PRIMARY KEY (variant_id, option_id),
    -- The value must belong to the option
    FOREIGN KEY (option_value_id, option_id)
        REFERENCES product_option_value (option_value_id, option_id)
);

CREATE TABLE product_image (
    image_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  INT NOT NULL REFERENCES product(product_id),
    variant_id  INT REFERENCES product_variant(variant_id),
    image_url   VARCHAR(500) NOT NULL,
    sort_order  INT NOT NULL DEFAULT 1
);

-- ------------------------------------------------------------
-- Orders
-- ------------------------------------------------------------

CREATE TABLE order_status (
    order_status_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status_name      VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE shipping_method (
    shipping_method_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    method_name         VARCHAR(50) NOT NULL UNIQUE,
    price               DECIMAL(10,2) NOT NULL
);

CREATE TABLE customer_order (
    order_id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id         INT NOT NULL REFERENCES customer(customer_id),
    order_status_id     INT NOT NULL REFERENCES order_status(order_status_id),
    order_date          TIMESTAMP,
    shipping_method_id  INT REFERENCES shipping_method(shipping_method_id),
    shipping_cost       DECIMAL(10,2),
    ship_name           VARCHAR(200),
    ship_address_line1  VARCHAR(255),
    ship_address_line2  VARCHAR(255),
    ship_city           VARCHAR(100),
    ship_region         VARCHAR(100),
    ship_postal_code    VARCHAR(20),
    ship_country        VARCHAR(100),
    subtotal            DECIMAL(10,2),
    discount_total      DECIMAL(10,2),
    order_total         DECIMAL(10,2),
    created_at          TIMESTAMP NOT NULL,
    updated_at          TIMESTAMP NOT NULL
);

-- One cart per customer (order_status_id 1 = Cart)
CREATE UNIQUE INDEX uq_one_cart_per_customer ON customer_order (customer_id) WHERE order_status_id = 1;

CREATE TABLE order_line (
    order_line_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         INT NOT NULL REFERENCES customer_order(order_id),
    variant_id       INT NOT NULL REFERENCES product_variant(variant_id),
    quantity         INT NOT NULL,
    product_name     VARCHAR(255),
    sku              VARCHAR(50),
    option_summary   VARCHAR(255),
    unit_price       DECIMAL(10,2),
    discount_amount  DECIMAL(10,2),
    UNIQUE (order_id, variant_id)
);

CREATE TABLE payment (
    payment_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id            INT NOT NULL REFERENCES customer_order(order_id),
    payment_method_id   INT REFERENCES payment_method(payment_method_id),
    provider_reference  VARCHAR(255) NOT NULL,
    amount              DECIMAL(10,2) NOT NULL,
    payment_status      VARCHAR(30) NOT NULL,
    created_at          TIMESTAMP NOT NULL
);

-- ------------------------------------------------------------
-- Promotions and reviews
-- ------------------------------------------------------------

CREATE TABLE promotion (
    promotion_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    promotion_name  VARCHAR(100) NOT NULL,
    description     TEXT,
    discount_type   VARCHAR(20) NOT NULL,
    discount_value  DECIMAL(10,2) NOT NULL,
    start_date      TIMESTAMP NOT NULL,
    end_date        TIMESTAMP NOT NULL
);

CREATE TABLE promotion_product (
    promotion_id  INT NOT NULL REFERENCES promotion(promotion_id),
    product_id    INT NOT NULL REFERENCES product(product_id),
    PRIMARY KEY (promotion_id, product_id)
);

CREATE TABLE review (
    review_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_line_id  INT NOT NULL UNIQUE REFERENCES order_line(order_line_id),
    rating         INT NOT NULL,
    comment        TEXT,
    created_at     TIMESTAMP NOT NULL
);

-- Review rating between 1 and 5
ALTER TABLE review ADD CONSTRAINT ck_review_rating CHECK (rating BETWEEN 1 AND 5);

